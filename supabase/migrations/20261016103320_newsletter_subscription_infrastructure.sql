create table if not exists public.newsletter_subscribers (
  id uuid primary key default gen_random_uuid(),
  email text not null unique,
  status text not null default 'active' check (status in ('active','unsubscribed')),
  consented_at timestamptz not null default now(),
  consent_version text not null,
  source_page text not null default 'unknown',
  source_context text not null default 'domain-change-popup',
  user_id uuid references auth.users(id) on delete set null,
  ip_hash text,
  resend_contact_id text,
  resend_sync_status text not null default 'pending' check (resend_sync_status in ('pending','synced','error')),
  last_resend_sync_at timestamptz,
  unsubscribed_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  metadata jsonb not null default '{}'::jsonb,
  constraint newsletter_subscribers_email_length check (char_length(email) between 5 and 254),
  constraint newsletter_subscribers_email_normalized check (email = lower(btrim(email))),
  constraint newsletter_subscribers_ip_hash check (ip_hash is null or char_length(ip_hash) = 64)
);

create index if not exists newsletter_subscribers_status_created_idx
  on public.newsletter_subscribers (status, created_at desc);
create index if not exists newsletter_subscribers_user_idx
  on public.newsletter_subscribers (user_id)
  where user_id is not null;

alter table public.newsletter_subscribers enable row level security;
revoke all on table public.newsletter_subscribers from public, anon, authenticated;
grant select, insert, update, delete on table public.newsletter_subscribers to service_role;

create table if not exists public.newsletter_subscription_events (
  id bigint generated by default as identity primary key,
  subscriber_id uuid references public.newsletter_subscribers(id) on delete cascade,
  event_type text not null check (event_type in ('subscribe','resubscribe','unsubscribe','sync_error')),
  occurred_at timestamptz not null default now(),
  source_page text not null default 'unknown',
  ip_hash text,
  metadata jsonb not null default '{}'::jsonb,
  constraint newsletter_subscription_events_ip_hash check (ip_hash is null or char_length(ip_hash) = 64)
);

create index if not exists newsletter_events_ip_time_idx
  on public.newsletter_subscription_events (ip_hash, occurred_at desc)
  where ip_hash is not null;
create index if not exists newsletter_events_subscriber_time_idx
  on public.newsletter_subscription_events (subscriber_id, occurred_at desc);

alter table public.newsletter_subscription_events enable row level security;
revoke all on table public.newsletter_subscription_events from public, anon, authenticated;
grant select, insert, update, delete on table public.newsletter_subscription_events to service_role;
grant usage, select on sequence public.newsletter_subscription_events_id_seq to service_role;
